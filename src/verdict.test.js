import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { parse, diff, findRisks, checkScrape, verdict, renderMarkdown } from './core.js'

const sample = (/** @type {string} */ f) => readFileSync(new URL(`../samples/${f}`, import.meta.url), 'utf8')
const BASE = sample('base.prom')
const OM = sample('real/prometheus-self.om.txt')

/** Compare like the Action does: verdict first, then the Markdown. */
function compare(/** @type {string} */ baseText, /** @type {string} */ headText, /** @type {{allowEmptyBase?: boolean}} */ opts = {}) {
  const base = parse(baseText), head = parse(headText)
  const d = diff(base, head)
  const v = verdict({ base, head, diff: d, ...opts })
  const md = renderMarkdown({ diff: d, risks: v.status === 'blocked' ? [] : findRisks(head, base), multiplier: 1, pricePer1k: 6.5, verdict: v })
  return { base, head, d, v, md }
}

const unreadable = /** @type {[string, string][]} */ ([
  ['JSON', '{"status":"success"}\n'],
  ['an HTML error page', '<html><body>502 Bad Gateway</body></html>\n'],
  ['a multi-line HTML page', '<!doctype html>\n<html>\n<head><title>Error</title></head>\n<body>Not found</body>\n</html>\n'],
  ['binary data', '\u0089PNG\r\n\u001a\n\u0000\u0000\u0000\rIHDR\u00ff\u00fe'],
  ['a gzip header', '\u001f\u008b\b\u0000\u0000\u0000\u0000\u0000\u0000\u0003'],
  ['plain prose', 'service unavailable, retry later\n'],
  ['a lone label set', '{a="1"}\n'],
])
const empty = /** @type {[string, string][]} */ ([
  ['an empty file', ''],
  ['only whitespace', '  \n\t\n\r\n'],
  ['only comments', '# generated by exporter\n# nothing yet\n'],
  ['only HELP/TYPE and no samples', '# HELP up Up.\n# TYPE up gauge\n'],
  ['only # EOF', '# EOF\n'],
])

for (const [label, text] of [...unreadable, ...empty]) {
  for (const side of /** @type {const} */ (['head', 'base'])) {
    test(`${label} as the ${side} is blocked: no delta, no savings, never green`, () => {
      const { v, md } = compare(side === 'head' ? BASE : text, side === 'head' ? text : BASE)
      assert.equal(v.status, 'blocked')
      assert.match(v.blockers[0], new RegExp(`^The ${side} scrape cannot be used`))
      assert.doesNotMatch(md, /🟢|🟠|🔴/)
      assert.doesNotMatch(md, /active series\*\*|\/month\*\*|−|→/)
      assert.match(md, /^<!-- cardinality-diff -->\n## ❌ Cardinality Diff/)
    })
  }
}

test('unreadable and empty are told apart, with the first problem quoted', () => {
  assert.equal(checkScrape(parse('{"a":1}')).state, 'unreadable')
  assert.match(checkScrape(parse('{"a":1}')).message, /1 malformed line, first at line 1: `/)
  assert.equal(checkScrape(parse('')).state, 'empty')
})

test('text from the scrape cannot break out of the message: one line, no backticks, bounded', () => {
  const nasty = checkScrape(parse('metric `evil` ' + 'x'.repeat(300) + '\n')).message
  assert.doesNotMatch(nasty, /\n|\r/)
  assert.ok(nasty.length < 400)
  assert.equal((nasty.match(/`/g) ?? []).length, 2)
  assert.doesNotMatch(checkScrape(parse('a 1 b\u001b[31m\u0007\n')).message, /[\u0000-\u001f]/)
})

test('an unreadable base cannot make everything look newly added', () => {
  const { v, d, md } = compare('{"status":"success"}', sample('head.prom'))
  assert.equal(v.status, 'blocked')
  assert.ok(d.rows.every((r) => r.status === 'added'), 'the raw diff would call everything new')
  assert.doesNotMatch(md, /new metric|\| added|\+\d/)
})

test('OpenMetrics without # EOF is provably incomplete; with it, complete', () => {
  assert.equal(checkScrape(parse(OM)).state, 'ok')
  assert.equal(parse(OM).eof, true)
  const cut = OM.replace(/# EOF\s*$/, '')
  assert.equal(cut.includes('# EOF'), false)
  assert.equal(checkScrape(parse(cut)).state, 'truncated')
  assert.match(checkScrape(parse(cut)).message, /without its required "# EOF"/)
  assert.equal(compare(BASE, cut).v.status, 'blocked')
  assert.equal(compare(cut, BASE).v.status, 'blocked')
})

test('every OpenMetrics-only marker makes a missing # EOF provable', () => {
  const docs = {
    '# UNIT': '# TYPE t counter\n# UNIT t seconds\nt_total 1\n',
    'info type': '# TYPE b info\nb_info{v="1"} 1\n',
    'stateset type': '# TYPE s stateset\ns{s="a"} 1\n',
    'gaugehistogram type': '# TYPE g gaugehistogram\ng_bucket{le="+Inf"} 1\ng_gcount 1\ng_gsum 1\n',
    'unknown type': '# TYPE u unknown\nu 1\n',
    exemplar: '# TYPE c counter\nc_total 1 # {trace_id="abc"} 1\n',
  }
  for (const [name, text] of Object.entries(docs)) {
    assert.equal(parse(text).openMetrics, true, name)
    assert.equal(checkScrape(parse(text)).state, 'truncated', name)
    assert.equal(checkScrape(parse(text + '# EOF\n')).state, 'ok', name)
  }
})

test('plain text format 0.0.4 is never called truncated: it has no end marker to miss', () => {
  for (const text of [BASE, sample('head.prom'), sample('real/node-exporter.prom'), '# TYPE a gauge\na 1\n', 'a 1']) {
    const r = parse(text)
    assert.equal(r.openMetrics, false)
    assert.notEqual(checkScrape(r).state, 'truncated')
  }
})

test('a scrape that was cut off cannot be a green improvement, wherever it was cut', () => {
  for (const [name, full] of [['text', sample('head.prom')], ['openmetrics', OM]]) {
    const lines = full.split('\n')
    const fullSeries = parse(full).series
    let flagged = 0
    // Every line boundary: the head is a strict prefix of itself, against the complete scrape as base.
    for (let n = 1; n < lines.length - 1; n++) {
      const prefix = lines.slice(0, n).join('\n') + '\n'
      const { head, d, v, md } = compare(full, prefix)
      if (head.series === fullSeries) continue // nothing was lost yet, so nothing to flag
      assert.ok(d.delta < 0 || head.series > 0 || v.status === 'blocked', `${name} cut at line ${n}`)
      assert.notEqual(v.status, 'ok', `${name} prefix of ${n} lines reports ok`)
      assert.ok(!md.includes('🟢'), `${name} prefix of ${n} lines is green`)
      flagged++
    }
    assert.ok(flagged > lines.length / 2, `${name}: most cut points were exercised`)
  }
})

test('a scrape cut in the middle of a line is marked incomplete and not green', () => {
  const full = sample('head.prom')
  for (const at of [150, 1000, 4097, 9000, 20000]) {
    const { v, md } = compare(full, full.slice(0, at))
    assert.notEqual(v.status, 'ok', `cut at byte ${at}`)
    assert.ok(!md.includes('🟢'))
  }
})

test('a few malformed lines keep the result but mark it incomplete and not green', () => {
  const noisy = BASE + 'this is not a metric\nanother_bad{ 1\n'
  const clean = compare(BASE, BASE)
  const { d, v, md } = compare(BASE, noisy)
  assert.equal(d.delta, clean.d.delta, 'the delta is unchanged from today')
  assert.equal(v.status, 'incomplete')
  assert.match(v.warnings[0], /^\*\*Incomplete result\.\*\* 2 malformed lines were skipped while parsing, so series on those lines are not counted/)
  assert.match(md, /## 🟠 Cardinality Diff/)
  assert.match(md, /_incomplete_/)
  assert.doesNotMatch(md, /🟢/)
  // Same data, no malformed lines: still green.
  assert.equal(clean.v.status, 'ok')
  assert.match(clean.md, /## 🟢 Cardinality Diff/)
})

test('malformed lines on the base side also make the result incomplete', () => {
  assert.equal(compare(BASE + 'junk\n', BASE).v.status, 'incomplete')
})

test('a legitimately removed family still reports its reduction, flagged for confirmation on text format', () => {
  const head = BASE.split('\n').filter((l) => !/^(# (HELP|TYPE) )?process_open_fds\b/.test(l)).join('\n')
  const { d, v, md } = compare(BASE, head)
  assert.equal(d.delta, -1)
  assert.equal(d.rows.find((r) => r.name === 'process_open_fds')?.status, 'removed')
  assert.equal(v.status, 'confirm')
  assert.match(md, /\*\*−1 active series\*\*/)
  assert.match(md, /process_open_fds/)
  assert.match(md, /Confirm the removed metrics were removed on purpose/)
  assert.match(md, /no end marker/)
  assert.doesNotMatch(md, /🟢/)
})

test('a reduction in an OpenMetrics scrape that ends with # EOF is trusted', () => {
  const head = OM.split('\n').filter((l) => !/^prometheus_http_requests(_total|_created)?\{code="503"/.test(l)).join('\n')
  const { d, v, md } = compare(OM, head)
  assert.ok(d.delta < 0)
  assert.equal(v.status, 'ok')
  assert.match(md, /## 🟢 Cardinality Diff/)
  assert.doesNotMatch(md, /Confirm/)
})

test('growth and no-change results are unchanged', () => {
  const grew = compare(BASE, sample('head.prom'))
  assert.equal(grew.v.status, 'ok')
  assert.equal(grew.v.warnings.length, 0)
  assert.match(grew.md, /## 🔴 Cardinality Diff/)
  assert.match(compare(BASE, BASE).md, /## 🟢 Cardinality Diff/)
})

test('first run: an empty base is refused unless explicitly allowed, and only an empty one', () => {
  assert.equal(compare('', BASE).v.status, 'blocked')
  const ok = compare('', BASE, { allowEmptyBase: true })
  assert.equal(ok.v.status, 'ok')
  assert.match(ok.v.warnings[0], /\*\*No base scrape\.\*\*/)
  assert.equal(ok.d.delta, parse(BASE).series)
  assert.match(ok.md, /every metric family counts as new/)
  // Opting in never excuses an unreadable or truncated base, or any empty head.
  assert.equal(compare('{"status":"success"}', BASE, { allowEmptyBase: true }).v.status, 'blocked')
  assert.equal(compare('# TYPE b info\nb_info 1\n', BASE, { allowEmptyBase: true }).v.status, 'blocked')
  assert.equal(compare(BASE, '', { allowEmptyBase: true }).v.status, 'blocked')
  assert.equal(compare('', '', { allowEmptyBase: true }).v.status, 'blocked')
  assert.equal(compare('# EOF\n', BASE, { allowEmptyBase: true }).v.status, 'ok')
})

test('single-scrape audit has no base to compare, but is still refused when unusable', () => {
  const names = { base: 'base', head: 'pasted' }
  const check = (/** @type {string} */ t) => verdict({ head: parse(t), names })
  assert.equal(check('').status, 'blocked')
  assert.match(check('{"a":1}').blockers[0], /^The pasted scrape cannot be used/)
  assert.equal(check('a 1\n').status, 'ok')
  assert.equal(check('a 1\nbad bad\n').status, 'incomplete')
})

test('without a verdict the Markdown is what it always was', () => {
  const base = parse(BASE), head = parse(sample('head.prom'))
  const o = { diff: diff(base, head), risks: findRisks(head, base), multiplier: 10, pricePer1k: 6.5 }
  assert.equal(renderMarkdown(o), renderMarkdown({ ...o, verdict: { status: 'ok', blockers: [], warnings: [] } }))
  assert.match(renderMarkdown({ ...o, errors: 3 }), /> 3 malformed line\(s\) were skipped while parsing\./)
})
